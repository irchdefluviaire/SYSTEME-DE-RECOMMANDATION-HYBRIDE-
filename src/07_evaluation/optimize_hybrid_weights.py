"""
Bayesian calibration of the hybrid recommendation score weights.

The objective is intentionally narrow: optimize ranking quality on the existing
candidate-offer reranking details. Relevance can be taken from the independent
proxy score generated by the ablation module, or from weak business verdicts.
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import optuna
import pandas as pd


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_INPUT = ROOT / "outputs" / "evaluation" / "pgvector_vs_graph" / "ablation_graph_rerank_details.csv"
OUT_DIR = ROOT / "outputs" / "evaluation" / "hybrid_weight_optimization"
FIG_DIR = ROOT / "rapport" / "figures" / "generated" / "evaluation"


COMPONENT_CANDIDATES = {
    "semantique": ["score_semantique", "score_sem"],
    "neo4j": ["score_neo4j", "score_graph", "taux_match"],
    "niveau_ncf": ["score_niveau_ncf", "niveau_ncf", "ncf_fit"],
    "secteur": ["score_secteur", "secteur_fit"],
    "localisation": ["score_localisation", "localisation_fit"],
}

VERDICT_RELEVANCE = {
    "hors_cible_actuel": 0.0,
    "vivier_a_developper": 1.0,
    "postuler_avec_plan_de_montee_en_competence": 2.0,
    "pret_a_postuler": 3.0,
}

optuna.logging.set_verbosity(optuna.logging.WARNING)


@dataclass(frozen=True)
class OptimizationConfig:
    input_path: Path = DEFAULT_INPUT
    n_trials: int = 250
    seed: int = 42
    k: int = 10
    relevance_source: str = "proxy"
    objective_name: str = "ndcg"
    min_weight: float = 0.001
    max_weight: float = 1.0


def _first_existing(df: pd.DataFrame, candidates: list[str]) -> str | None:
    for col in candidates:
        if col in df.columns:
            return col
    return None


def detect_components(df: pd.DataFrame) -> dict[str, str]:
    components: dict[str, str] = {}
    for name, candidates in COMPONENT_CANDIDATES.items():
        col = _first_existing(df, candidates)
        if col is not None:
            components[name] = col
    if len(components) < 2:
        raise ValueError(
            "At least two score components are required. Current columns do not "
            "allow meaningful hybrid-weight optimization."
        )
    return components


def add_relevance(df: pd.DataFrame, source: str) -> pd.DataFrame:
    out = df.copy()
    if source == "proxy":
        if "proxy_relevance" not in out.columns:
            raise ValueError("Column 'proxy_relevance' is required with relevance_source='proxy'.")
        out["relevance"] = pd.to_numeric(out["proxy_relevance"], errors="coerce").fillna(0.0)
    elif source == "verdict":
        verdict_col = _first_existing(out, ["verdict_recrutement", "verdict"])
        if verdict_col is None:
            raise ValueError("A verdict column is required with relevance_source='verdict'.")
        out["relevance"] = out[verdict_col].map(VERDICT_RELEVANCE).fillna(0.0)
    else:
        raise ValueError("relevance_source must be either 'proxy' or 'verdict'.")
    out["binary_relevance"] = 0
    for _, idx in out.groupby("candidat_id", sort=False).groups.items():
        group = out.loc[idx]
        if source == "proxy":
            threshold = max(0.35, float(np.quantile(group["relevance"], 0.70)))
        else:
            threshold = 2.0
        out.loc[idx, "binary_relevance"] = (group["relevance"] >= threshold).astype(int)
        if out.loc[idx, "binary_relevance"].sum() == 0 and len(group):
            best_idx = group["relevance"].astype(float).idxmax()
            out.loc[best_idx, "binary_relevance"] = 1
    return out


def normalize_weights(raw: dict[str, float]) -> dict[str, float]:
    total = sum(max(float(v), 0.0) for v in raw.values())
    if total <= 0:
        equal = 1.0 / len(raw)
        return {key: equal for key in raw}
    return {key: float(value) / total for key, value in raw.items()}


def score_with_weights(df: pd.DataFrame, components: dict[str, str], weights: dict[str, float]) -> pd.Series:
    score = pd.Series(np.zeros(len(df)), index=df.index, dtype=float)
    for name, col in components.items():
        values = pd.to_numeric(df[col], errors="coerce").fillna(0.0).clip(lower=0.0, upper=1.0)
        score += weights[name] * values
    return score.clip(lower=0.0, upper=1.0)


def ndcg_at_k_for_group(group: pd.DataFrame, score_col: str, k: int) -> float:
    ranked = group.sort_values(score_col, ascending=False).head(k)
    gains = ranked["relevance"].astype(float).to_numpy()
    discounts = np.array([math.log2(i + 2) for i in range(len(gains))], dtype=float)
    dcg = float(np.sum(gains / discounts)) if len(gains) else 0.0

    ideal = group.sort_values("relevance", ascending=False).head(k)
    ideal_gains = ideal["relevance"].astype(float).to_numpy()
    ideal_discounts = np.array([math.log2(i + 2) for i in range(len(ideal_gains))], dtype=float)
    idcg = float(np.sum(ideal_gains / ideal_discounts)) if len(ideal_gains) else 0.0
    return dcg / idcg if idcg > 0 else 0.0


def mean_ndcg_at_k(df: pd.DataFrame, score_col: str, k: int) -> float:
    values = [
        ndcg_at_k_for_group(group, score_col=score_col, k=k)
        for _, group in df.groupby("candidat_id", sort=False)
    ]
    return float(np.mean(values)) if values else 0.0


def binary_metrics_at_k_for_group(group: pd.DataFrame, score_col: str, k: int) -> dict[str, float]:
    ranked = group.sort_values(score_col, ascending=False).head(k)
    hits = ranked["binary_relevance"].astype(int).to_numpy()
    n_relevant = int(group["binary_relevance"].astype(int).sum())
    precision = float(hits.sum() / k) if k else 0.0
    recall = float(hits.sum() / n_relevant) if n_relevant else 0.0
    mrr = 0.0
    for i, hit in enumerate(hits, 1):
        if hit:
            mrr = 1.0 / i
            break
    return {"precision": precision, "recall": recall, "mrr": mrr}


def mean_ranking_metrics(df: pd.DataFrame, score_col: str, k: int) -> dict[str, float]:
    rows = []
    for _, group in df.groupby("candidat_id", sort=False):
        row = binary_metrics_at_k_for_group(group, score_col, k)
        row["ndcg"] = ndcg_at_k_for_group(group, score_col, k)
        rows.append(row)
    if not rows:
        return {"ndcg": 0.0, "precision": 0.0, "recall": 0.0, "mrr": 0.0}
    return {
        key: float(np.mean([row[key] for row in rows]))
        for key in ("ndcg", "precision", "recall", "mrr")
    }


def objective_value(metrics: dict[str, float], objective_name: str) -> float:
    if objective_name == "ndcg":
        return metrics["ndcg"]
    if objective_name == "ndcg_recall_precision":
        return (metrics["ndcg"] + metrics["recall"] + metrics["precision"]) / 3.0
    if objective_name == "mrr_precision":
        return (metrics["mrr"] + metrics["precision"]) / 2.0
    raise ValueError(
        "objective_name must be one of: ndcg, ndcg_recall_precision, mrr_precision."
    )


def optimize_weights(df: pd.DataFrame, components: dict[str, str], config: OptimizationConfig) -> tuple[optuna.Study, pd.DataFrame]:
    def objective(trial: optuna.Trial) -> float:
        raw = {
            name: trial.suggest_float(f"w_{name}", config.min_weight, config.max_weight)
            for name in components
        }
        weights = normalize_weights(raw)
        scored = df.copy()
        scored["score_hybride_optuna"] = score_with_weights(scored, components, weights)
        metrics = mean_ranking_metrics(scored, "score_hybride_optuna", config.k)
        return objective_value(metrics, config.objective_name)

    sampler = optuna.samplers.TPESampler(seed=config.seed)
    study = optuna.create_study(direction="maximize", sampler=sampler)
    study.optimize(objective, n_trials=config.n_trials, show_progress_bar=False)

    trials = study.trials_dataframe(attrs=("number", "value", "params", "state"))
    return study, trials


def candidate_weight_sets(optuna_weights: dict[str, float], component_names: list[str]) -> dict[str, dict[str, float]]:
    candidates: dict[str, dict[str, float]] = {"optuna_best": optuna_weights}
    equal = 1.0 / len(component_names)
    candidates["poids_egaux"] = {name: equal for name in component_names}
    for name in component_names:
        candidates[f"pur_{name}"] = {other: 1.0 if other == name else 0.0 for other in component_names}
    return candidates


def evaluate_weight_sets(
    df: pd.DataFrame,
    components: dict[str, str],
    weight_sets: dict[str, dict[str, float]],
    k: int,
) -> dict[str, dict[str, float]]:
    scores: dict[str, dict[str, float]] = {}
    for name, weights in weight_sets.items():
        scored = df.copy()
        scored["score_candidate_weights"] = score_with_weights(scored, components, weights)
        scores[name] = mean_ranking_metrics(scored, "score_candidate_weights", k)
    return scores


def summarize_baselines(df: pd.DataFrame, k: int) -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    if "score_sem" in df.columns:
        out["pgvector_semantique"] = mean_ranking_metrics(df, "score_sem", k)
    if "score_semantique" in df.columns:
        out["pgvector_semantique"] = mean_ranking_metrics(df, "score_semantique", k)
    if "score_hybride" in df.columns:
        out["score_hybride_actuel"] = mean_ranking_metrics(df, "score_hybride", k)
    return out


def build_output_details(df: pd.DataFrame, components: dict[str, str], weights: dict[str, float], k: int) -> pd.DataFrame:
    out = df.copy()
    out["score_hybride_optuna"] = score_with_weights(out, components, weights)
    out["rank_optuna"] = (
        out.groupby("candidat_id")["score_hybride_optuna"]
        .rank(method="first", ascending=False)
        .astype(int)
    )
    out["top10_optuna"] = out["rank_optuna"] <= k
    return out


def plot_trials(trials: pd.DataFrame, suffix: str = "") -> Path:
    fig, ax = plt.subplots(figsize=(8.8, 4.8))
    valid = trials[trials["value"].notna()].copy()
    ax.plot(valid["number"], valid["value"], color="#1f5aa6", linewidth=1.3, alpha=0.8)
    ax.scatter(valid["number"], valid["value"], color="#1f5aa6", s=18, alpha=0.65)
    ax.axhline(valid["value"].max(), color="#b42318", linestyle="--", linewidth=1.2)
    ax.set_title("Optimisation bayesienne des poids du score hybride")
    ax.set_xlabel("Essai Optuna")
    ax.set_ylabel("Objectif moyen")
    ax.grid(alpha=0.25)
    fig.tight_layout()
    out_path = OUT_DIR / f"hybrid_weights_optimization_trials{suffix}.png"
    fig_path = FIG_DIR / f"hybrid_weights_optimization_trials{suffix}.png"
    for path in (out_path, fig_path):
        fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    return fig_path


def plot_weights(weights: dict[str, float], suffix: str = "") -> Path:
    fig, ax = plt.subplots(figsize=(7.8, 4.6))
    labels = list(weights.keys())
    values = [weights[label] for label in labels]
    colors = ["#1d4ed8", "#15803d", "#f59e0b", "#7c3aed", "#0f766e"][: len(labels)]
    bars = ax.bar(labels, values, color=colors, width=0.62)
    ax.set_ylim(0, max(values) * 1.25 if values else 1)
    ax.set_title("Ponderations retenues par optimisation")
    ax.set_ylabel("Poids normalise")
    ax.grid(axis="y", alpha=0.25)
    for bar, value in zip(bars, values):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.01, f"{value:.3f}", ha="center")
    fig.tight_layout()
    out_path = OUT_DIR / f"hybrid_weights_best{suffix}.png"
    fig_path = FIG_DIR / f"hybrid_weights_best{suffix}.png"
    for path in (out_path, fig_path):
        fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    return fig_path


def plot_ndcg_comparison(metrics: dict[str, dict[str, float]], suffix: str = "") -> Path:
    fig, ax = plt.subplots(figsize=(8.0, 4.6))
    labels = list(metrics.keys())
    values = [metrics[label]["ndcg"] for label in labels]
    bars = ax.bar(labels, values, color=["#64748b", "#2563eb", "#15803d"][: len(labels)], width=0.58)
    ax.set_ylim(0, min(1.0, max(values) * 1.25 if values else 1.0))
    ax.set_title("Comparaison NDCG@10 avant et apres calibration")
    ax.set_ylabel("NDCG@10 moyen")
    ax.tick_params(axis="x", rotation=15)
    ax.grid(axis="y", alpha=0.25)
    for bar, value in zip(bars, values):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.01, f"{value:.4f}", ha="center")
    fig.tight_layout()
    out_path = OUT_DIR / f"hybrid_weights_ndcg_comparison{suffix}.png"
    fig_path = FIG_DIR / f"hybrid_weights_ndcg_comparison{suffix}.png"
    for path in (out_path, fig_path):
        fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    return fig_path


def plot_multi_objective_weights(comparison: pd.DataFrame) -> Path:
    plot_df = comparison.copy()
    labels = {
        "ndcg": "NDCG",
        "ndcg_recall_precision": "NDCG+R+P",
        "mrr_precision": "MRR+P",
    }
    plot_df["label"] = plot_df["objective"].map(labels).fillna(plot_df["objective"])

    x = np.arange(len(plot_df))
    width = 0.36
    fig, ax = plt.subplots(figsize=(7.5, 4.3))
    bars_sem = ax.bar(x - width / 2, plot_df["w_semantique"], width, label="Score semantique", color="#2563eb")
    bars_graph = ax.bar(x + width / 2, plot_df["w_neo4j"], width, label="Score Neo4j", color="#15803d")
    ax.set_title("Ponderations retenues selon la fonction objectif")
    ax.set_ylabel("Poids normalise")
    ax.set_ylim(0, 1.05)
    ax.set_xticks(x)
    ax.set_xticklabels(plot_df["label"])
    ax.legend()
    ax.grid(axis="y", alpha=0.25)
    ax.bar_label(bars_sem, fmt="%.2f", padding=3, fontsize=9)
    ax.bar_label(bars_graph, fmt="%.2f", padding=3, fontsize=9)
    fig.tight_layout()
    out_path = OUT_DIR / "hybrid_weights_multi_objective_comparison.png"
    fig_path = FIG_DIR / "hybrid_weights_multi_objective_comparison.png"
    for path in (out_path, fig_path):
        fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    return fig_path


def run(config: OptimizationConfig) -> dict[str, Any]:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    FIG_DIR.mkdir(parents=True, exist_ok=True)

    df = pd.read_csv(config.input_path)
    if "candidat_id" not in df.columns:
        raise ValueError("Column 'candidat_id' is required to compute grouped NDCG@10.")

    df = add_relevance(df, config.relevance_source)
    components = detect_components(df)
    baselines = summarize_baselines(df, config.k)

    study, trials = optimize_weights(df, components, config)
    raw_best = {name: float(study.best_params[f"w_{name}"]) for name in components}
    optuna_weights = normalize_weights(raw_best)

    weight_sets = candidate_weight_sets(optuna_weights, list(components))
    weight_set_metrics = evaluate_weight_sets(df, components, weight_sets, config.k)
    weight_set_objectives = {
        name: objective_value(metrics, config.objective_name)
        for name, metrics in weight_set_metrics.items()
    }
    retained_weight_set = max(weight_set_objectives, key=weight_set_objectives.get)
    best_weights = weight_sets[retained_weight_set]

    details = build_output_details(df, components, best_weights, config.k)
    optimized_metrics = mean_ranking_metrics(details, "score_hybride_optuna", config.k)
    metrics = {**baselines, "score_hybride_optuna": optimized_metrics}

    suffix = config.objective_name
    trials_path = OUT_DIR / f"hybrid_weight_trials_{suffix}.csv"
    details_path = OUT_DIR / f"optimized_ranking_details_{suffix}.csv"
    summary_path = OUT_DIR / f"best_weights_{suffix}.json"
    trials.to_csv(trials_path, index=False)
    details.to_csv(details_path, index=False)

    if config.objective_name == "ndcg":
        trials.to_csv(OUT_DIR / "hybrid_weight_trials.csv", index=False)
        details.to_csv(OUT_DIR / "optimized_ranking_details.csv", index=False)

    summary = {
        "objective": config.objective_name,
        "objective_formula": {
            "ndcg": f"NDCG@{config.k}",
            "ndcg_recall_precision": f"(NDCG@{config.k} + Recall@{config.k} + Precision@{config.k}) / 3",
            "mrr_precision": f"(MRR@{config.k} + Precision@{config.k}) / 2",
        }[config.objective_name],
        "optimizer": "Optuna TPESampler",
        "n_trials": config.n_trials,
        "seed": config.seed,
        "relevance_source": config.relevance_source,
        "input_path": str(config.input_path.relative_to(ROOT)),
        "n_rows": int(len(df)),
        "n_candidates": int(df["candidat_id"].nunique()),
        "components": components,
        "best_trial": int(study.best_trial.number),
        "best_value": round(float(study.best_value), 6),
        "retained_weight_set": retained_weight_set,
        "best_weights": {key: round(value, 6) for key, value in best_weights.items()},
        "candidate_weight_set_objectives": {
            key: round(float(value), 6)
            for key, value in sorted(weight_set_objectives.items(), key=lambda item: item[1], reverse=True)
        },
        "candidate_weight_set_metrics": {
            key: {metric: round(float(value), 6) for metric, value in metric_values.items()}
            for key, metric_values in weight_set_metrics.items()
        },
        "metrics": {
            key: {metric: round(float(value), 6) for metric, value in metric_values.items()}
            for key, metric_values in metrics.items()
        },
        "outputs": {
            "trials_csv": str(trials_path.relative_to(ROOT)),
            "details_csv": str(details_path.relative_to(ROOT)),
        },
    }

    figure_suffix = f"_{config.objective_name}"
    trials_figure = plot_trials(trials, figure_suffix)
    weights_figure = plot_weights(best_weights, figure_suffix)
    comparison_figure = plot_ndcg_comparison(metrics, figure_suffix)
    summary["outputs"].update(
        {
            "trials_figure": str(trials_figure.relative_to(ROOT)),
            "weights_figure": str(weights_figure.relative_to(ROOT)),
            "comparison_figure": str(comparison_figure.relative_to(ROOT)),
        }
    )
    summary_path.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    if config.objective_name == "ndcg":
        (OUT_DIR / "best_weights.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    return summary


def run_many(base_config: OptimizationConfig, objectives: list[str]) -> dict[str, Any]:
    summaries = []
    for objective in objectives:
        config = OptimizationConfig(
            input_path=base_config.input_path,
            n_trials=base_config.n_trials,
            seed=base_config.seed,
            k=base_config.k,
            relevance_source=base_config.relevance_source,
            objective_name=objective,
            min_weight=base_config.min_weight,
            max_weight=base_config.max_weight,
        )
        summaries.append(run(config))

    rows = []
    for item in summaries:
        row = {
            "objective": item["objective"],
            "objective_formula": item["objective_formula"],
            "best_trial": item["best_trial"],
            "best_value": item["best_value"],
            "retained_weight_set": item["retained_weight_set"],
        }
        for name, value in item["best_weights"].items():
            row[f"w_{name}"] = value
        for metric, value in item["metrics"]["score_hybride_optuna"].items():
            row[f"optuna_{metric}"] = value
        rows.append(row)

    comparison = pd.DataFrame(rows)
    comparison_path = OUT_DIR / "multi_objective_weight_comparison.csv"
    comparison.to_csv(comparison_path, index=False)
    comparison_figure = plot_multi_objective_weights(comparison)

    summary = {
        "objectives": objectives,
        "input_path": str(base_config.input_path.relative_to(ROOT)),
        "n_trials_per_objective": base_config.n_trials,
        "comparison_csv": str(comparison_path.relative_to(ROOT)),
        "comparison_figure": str(comparison_figure.relative_to(ROOT)),
        "summaries": summaries,
    }
    (OUT_DIR / "multi_objective_weight_comparison.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    return summary


def parse_args() -> OptimizationConfig:
    parser = argparse.ArgumentParser(description="Optimize hybrid score weights by maximizing NDCG@10.")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="Reranking details CSV.")
    parser.add_argument("--n-trials", type=int, default=250, help="Number of Optuna trials.")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for Optuna TPESampler.")
    parser.add_argument("--k", type=int, default=10, help="Cutoff for NDCG@k.")
    parser.add_argument("--relevance-source", choices=["proxy", "verdict"], default="proxy")
    parser.add_argument(
        "--objective",
        choices=["ndcg", "ndcg_recall_precision", "mrr_precision", "all"],
        default="ndcg",
    )
    args = parser.parse_args()
    return OptimizationConfig(
        input_path=args.input,
        n_trials=args.n_trials,
        seed=args.seed,
        k=args.k,
        relevance_source=args.relevance_source,
        objective_name=args.objective,
    )


def main() -> None:
    config = parse_args()
    if config.objective_name == "all":
        summary = run_many(config, ["ndcg", "ndcg_recall_precision", "mrr_precision"])
    else:
        summary = run(config)
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
