class AgentState(MessagesState, total=False):
    candidat_id: str
    top_k: int
    backend: str
    use_case: str
    user_query: str
    tool_calls: list[dict[str, Any]]
    tool_results: list[dict[str, Any]]
    context: dict[str, Any]
