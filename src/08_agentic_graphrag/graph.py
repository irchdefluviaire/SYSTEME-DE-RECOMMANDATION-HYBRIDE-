def generate_final_answer(state: AgentState) -> AgentState:
    result = state.get("result", {})
    use_case = state.get("use_case", "recherche_generale")
    query = state.get("user_query", "")
    top_k = int(state.get("top_k", 5))

    # Cas erreur totale â€” pas besoin de LLM
    if result.get("errors") and len(result) == 1:
        answer = _render_errors(result["errors"])
        critic = {"decision": "revise", "reason": "all_tools_failed"}
        traces = [*state.get("traces", []), "generate_final_answer"]
        return {
            **state,
            "critic": critic,
            "traces": traces,
            "messages": [*state.get("messages", []), AIMessage(content=answer)],
        }

    # Diagnostic â€” rÃ©ponse structurÃ©e sans LLM
    if use_case == "diagnostic":
        answer = _render_diagnostic(result)
        critic = {"decision": "accept", "source": "template"}
        traces = [*state.get("traces", []), "generate_final_answer"]
        return {
            **state,
            "critic": critic,
            "traces": traces,
            "messages": [*state.get("messages", []), AIMessage(content=answer)],
        }

    # Tous les autres cas â€” synthÃ¨se LLM avec fallback template
    context_text = _build_context_text(result, use_case, top_k, state)

    try:
        from llm_client import get_llm_client  # noqa: PLC0415
        llm = get_llm_client()
        user_prompt = (
            f"Question de l'utilisateur : {query}\n\n"
            "=== DONNÃ‰ES EXTRAITES DES BASES DE DONNÃ‰ES ===\n"
            f"{context_text}\n"
            "=== FIN DES DONNÃ‰ES ===\n\n"
            "RÃ©dige une rÃ©ponse en langage naturel, en franÃ§ais, structurÃ©e avec ## titres et listes Ã  puces.\n"
            "Pour chaque information clÃ© utilisÃ©e, cite sa source entre crochets (chunk_id, source_uri, id pgvector, etc.).\n"
            "Ne mentionne que ce qui est prÃ©sent dans les donnÃ©es ci-dessus."
        )
        answer = llm.chat(_SYSTEM_CONSEILLER, user_prompt)
        critic = critique_answer(answer, context_text)
        critic["source"] = "openrouter"
        critic["model"] = llm.model
        log.info("RÃ©ponse gÃ©nÃ©rÃ©e via OpenRouter (model=%s)", llm.model)
    except Exception as exc:
        log.error("LLM OpenRouter indisponible (%s) â€” donnÃ©es brutes affichÃ©es", exc)
        # Fallback lisible : encadre les donnÃ©es brutes avec un message d'avertissement
        answer = (
            f"âš ï¸ *Le service LLM est temporairement indisponible ({exc.__class__.__name__}).*\n\n"
            "Voici les donnÃ©es brutes rÃ©cupÃ©rÃ©es :\n\n"
            f"{context_text}"
        )
        critic = critique_answer(context_text, result)
        critic["source"] = "template"
        critic["llm_error"] = str(exc)

    traces = [*state.get("traces", []), "generate_final_answer", "answer_critic"]
    return {
        **state,
        "critic": critic,
        "traces": traces,
        "messages": [*state.get("messages", []), AIMessage(content=answer)],
    }


# â”€â”€ Renderers (utilisÃ©s comme contexte pour le LLM ou en fallback) â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

def route_after_critic(state: AgentState) -> str:
    critic = state.get("critic", {}) or {}
    if critic.get("decision") == "revise" and int(state.get("revision_count", 0) or 0) < 1:
        return "revise"
    return "accept"


def expand_context(state: AgentState) -> AgentState:
    """Add one extra retrieval pass when grounding is too weak."""

    query = state.get("user_query", "")
    top_k = min(int(state.get("top_k", 5)) + 3, 10)
    existing = [call.get("name") for call in state.get("tool_calls", [])]
    extra_calls: list[dict[str, Any]] = []

    if "pgvector_document_search" not in existing:
        extra_calls.append(_tool_call("pgvector_document_search", query=query, top_k=top_k))
    if "pgvector_semantic_search" not in existing:
        extra_calls.append(
            _tool_call(
                "pgvector_semantic_search",
                query=query,
                kinds=["OFFRE_EMPLOI", "METIER", "COMPETENCE"],
                top_k=top_k,
            )
        )
    if "neo4j_graph_query" not in existing and state.get("use_case") != "diagnostic":
        extra_calls.append(_tool_call("neo4j_graph_query", query=query, top_k=top_k))

    traces = [*state.get("traces", []), "answer_critic:revise", "expand_context"]
    return {
        **state,
        "top_k": top_k,
        "revision_count": int(state.get("revision_count", 0) or 0) + 1,
        "tool_calls": extra_calls or state.get("tool_calls", []),
        "traces": traces,
    }


def _render_errors(errors: list[dict[str, Any]]) -> str:
    lines = ["Aucun outil n'a pu retourner de contexte exploitable.", ""]
    for err in errors:
        lines.append(f"- {err.get('tool')}: {err.get('error')}")
    return "\n".join(lines)


def _render_diagnostic(result: dict[str, Any]) -> str:
    lines = ["Diagnostic de l'instance connectÃ©e:", ""]
    for key, value in result.get("status", {}).items():
        lines.append(f"- {key}: {value}")
    return "\n".join(lines)


def _render_documents(docs: list[dict[str, Any]]) -> str:
    lines = ["Chunks de rÃ©fÃ©rentiels trouvÃ©s dans pgvector:", ""]
    for i, doc in enumerate(docs, 1):
        chunk_id = doc.get("chunk_id", f"chunk_{i}")
        source = doc.get("source", "?")
        page = doc.get("page_number", "?")
        sim = doc.get("cosine_sim", 0)
        section = doc.get("section_title") or doc.get("subsection_title", "")
        lines.append(
            f"{i}. [Source: \"{source}\", chunk: {chunk_id}, p.{page}]"
            + (f" â€” {section}" if section else "")
            + f" (sim={float(sim):.3f})"
        )
        snippet = str(doc.get("parent_context") or doc.get("chunk_text", "")).replace("\n", " ")
        lines.append(f"   Extrait: {snippet[:300]}")
    if not docs:
        lines.append("Aucun document pertinent trouvÃ© dans pgvector.")
    return "\n".join(lines)


def _render_graph_rows(graph_result: dict[str, Any]) -> str:
    rows = graph_result.get("rows", [])
    plan = graph_result.get("plan", {})
    source = graph_result.get("source", "template")
    intent = plan.get("intent", "non_prÃ©cisÃ©")
    lines = [
        f"RÃ©sultats Neo4j (intent={intent}, source={source}):",
        "",
    ]
    for i, row in enumerate(rows, 1):
        # Champs citables mis en avant
        citable = []
        for key in ("source_uri", "chunk_id", "source_id", "code_isco"):
            if row.get(key):
                citable.append(f"{key}={row[key]}")
        label_keys = ("competence", "metier", "titre", "document", "section", "candidat_id")
        label = next((str(row[k]) for k in label_keys if row.get(k)), None)
        rest = " | ".join(
            f"{k}: {v}" for k, v in row.items()
            if k not in ("source_uri", "chunk_id", "source_id") and v not in (None, "", [])
        )
        ref = f" [{', '.join(citable)}]" if citable else ""
        lines.append(f"{i}. {label or ''}{ref} â€” {rest}")
    if not rows:
        lines.append("Aucun rÃ©sultat trouvÃ© dans Neo4j pour cette question.")
    return "\n".join(lines)


def _render_semantic_and_graph(result: dict[str, Any], top_k: int) -> str:
    lines = ["Contexte rÃ©cupÃ©rÃ© par les outils:", ""]

    semantic_results = result.get("semantic_results", {})
    if semantic_results:
        lines.append("pgvector â€” recherche sÃ©mantique hybride:")
        for kind, rows in semantic_results.items():
            lines.append(f"  {kind}:")
            for i, row in enumerate(rows[:top_k], 1):
                score = row.get("dense_score", row.get("cosine_sim", row.get("rrf_score", 0)))
                lexical = row.get("lexical_score", 0)
                entity_id = row.get("entity_id", "")
                label = row.get("label", "")
                lines.append(
                    f"    {i}. [pgvector: \"{label}\", id: {entity_id}] "
                    f"dense={float(score or 0):.3f} lexical={float(lexical or 0):.3f}"
                )

    graph_result = result.get("graph")
    if graph_result:
        lines.extend(["", "Neo4j â€” relations graphe:"])
        rows = graph_result.get("rows", [])
        for i, row in enumerate(rows[:top_k], 1):
            rendered = " | ".join(f"{k}={v}" for k, v in row.items())
            lines.append(f"  {i}. {rendered}")
        if not rows:
            lines.append("  Aucun lien graphe retournÃ©.")

    docs = result.get("documents") or []
    if docs:
        lines.extend(["", "pgvector â€” appuis rÃ©fÃ©rentiels:"])
        for doc in docs[:3]:
            lines.append(
                f"- {doc.get('source')} p.{doc.get('page_number')}: "
                f"{str(doc.get('chunk_text', '')).replace(chr(10), ' ')[:180]}"
            )

    if result.get("errors"):
        lines.extend(["", "Outils en erreur:"])
        for err in result["errors"]:
            lines.append(f"- {err.get('tool')}: {err.get('error')}")

    return "\n".join(lines).strip()


def _render_global_summary(summary: dict[str, Any], docs: list[dict[str, Any]]) -> str:
    lines = ["Synthese globale des stockages et du graphe:", ""]

    status = summary.get("status") or {}
    if status:
        lines.append("Etat des services:")
        for key, value in status.items():
            lines.append(f"- {key}: {value}")
        lines.append("")

    sections = [
        ("Noeuds Neo4j", "graph_counts", "label"),
        ("Secteurs les plus representes", "top_secteurs", "secteur"),
        ("Exemples de metiers", "top_metiers", "metier"),
        ("Exemples de competences", "top_competences", "competence"),
        ("Entites pgvector", "pgvector_counts", "entity_kind"),
        ("Sources documentaires indexees", "document_sources", "source"),
    ]
    for title, key, label_key in sections:
        rows = summary.get(key) or []
        if not rows:
            continue
        lines.append(title + ":")
        for row in rows[:10]:
            label = row.get(label_key, "")
            count = row.get("n", row.get("n_chunks", ""))
            suffix = f" ({count})" if count != "" else ""
            details = " | ".join(
                f"{k}={v}"
                for k, v in row.items()
                if k not in {label_key, "n", "n_chunks"} and v not in (None, "")
            )
            lines.append(f"- {label}{suffix}" + (f" | {details}" if details else ""))
        lines.append("")

    if docs:
        lines.append("Appuis documentaires recuperes:")
        for doc in docs[:5]:
            snippet = str(doc.get("chunk_text", "")).replace("\n", " ")[:220]
            lines.append(
                f"- [Source: {doc.get('source')}, chunk: {doc.get('chunk_id')}, "
                f"p.{doc.get('page_number')}] {snippet}"
            )

    for err_key in ("neo4j_error", "pgvector_error"):
        if summary.get(err_key):
            lines.append(f"{err_key}: {summary[err_key]}")
    return "\n".join(lines).strip()


def _render_candidate_recommendation(state: AgentState, result: dict[str, Any]) -> str:
    candidat = result.get("candidat", {})
